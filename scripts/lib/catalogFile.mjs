import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

export const CATALOG_FILE = fileURLToPath(new URL('../../src/data/catalog.data.ts', import.meta.url));

/** The text of src/data/catalog.data.ts for a catalog document (always the same text for the same document). */
export function catalogFileText(doc) {
  return `// Generated by scripts/export-catalog.mjs. Do not edit by hand: change the offer in the agenda and publish it.
import type { CatalogDoc } from './catalogTypes';

export const CATALOG: CatalogDoc = ${JSON.stringify(doc, null, 1)};
`;
}

/** Writes the file only when its text would change. Returns true when it wrote. */
export function writeCatalogFile(doc, out = CATALOG_FILE) {
  const text = catalogFileText(doc);
  if (existsSync(out) && readFileSync(out, 'utf8') === text) return false;
  writeFileSync(out, text, 'utf8');
  return true;
}
